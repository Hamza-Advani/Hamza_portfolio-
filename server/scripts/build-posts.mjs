// Compiles the technical articles in server/content/posts/*.md into
// server/src/data/posts/index.js (committed), so the API never parses Markdown at runtime.
//
//   npm run build:posts -w server
//
// Supported Markdown (deliberately small): front matter, ## / ### headings, paragraphs,
// - and 1. lists, > quotes, ``` fenced code, `inline code`, **bold**, *italic*, [links](url).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readingTime } from '../src/utils/text.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, '../content/posts');
const OUT = path.resolve(here, '../src/data/posts/index.js');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function inline(text) {
  const codes = [];
  let s = text.replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = esc(s)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, href) =>
      /^https?:\/\//.test(href) ? `<a href="${href}" target="_blank" rel="noopener noreferrer">${t}</a>` : `<a href="${href}">${t}</a>`,
    );
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(codes[Number(i)])}</code>`);
}

function markdown(md) {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let para = [];
  let list = null; // { tag, items }
  const flushPara = () => {
    if (para.length) out.push(`<p>${inline(para.join(' '))}</p>`);
    para = [];
  };
  const flushList = () => {
    if (list) out.push(`<${list.tag}>${list.items.map((i) => `<li>${inline(i)}</li>`).join('')}</${list.tag}>`);
    list = null;
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const fence = line.match(/^```(\w*)\s*$/);
    if (fence) {
      flushPara();
      flushList();
      const buf = [];
      for (i++; i < lines.length && !/^```\s*$/.test(lines[i]); i++) buf.push(lines[i]);
      const cls = fence[1] ? ` class="language-${fence[1]}"` : '';
      out.push(`<pre><code${cls}>${esc(buf.join('\n'))}</code></pre>`);
      continue;
    }
    let m;
    if (!line.trim()) { flushPara(); flushList(); continue; }
    if ((m = line.match(/^(#{2,4})\s+(.*)$/))) { flushPara(); flushList(); out.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); continue; }
    if ((m = line.match(/^>\s?(.*)$/))) { flushPara(); flushList(); out.push(`<blockquote><p>${inline(m[1])}</p></blockquote>`); continue; }
    if ((m = line.match(/^\s*[-*]\s+(.*)$/)) || (m = line.match(/^\s*\d+\.\s+(.*)$/))) {
      flushPara();
      const tag = /^\s*\d+\./.test(line) ? 'ol' : 'ul';
      if (!list || list.tag !== tag) { flushList(); list = { tag, items: [] }; }
      list.items.push(m[1]);
      continue;
    }
    if (list && /^\s{2,}\S/.test(line)) { list.items[list.items.length - 1] += ' ' + line.trim(); continue; }
    flushList();
    para.push(line.trim());
  }
  flushPara();
  flushList();
  return out.join('\n');
}

function parse(file) {
  const raw = fs.readFileSync(path.join(SRC, file), 'utf8').replace(/\r\n/g, '\n');
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!fm) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const l of fm[1].split('\n')) {
    const m = l.match(/^(\w+):\s*(.*)$/);
    if (m) meta[m[1]] = m[2].trim().replace(/^"(.*)"$/, '$1');
  }
  for (const k of ['title', 'slug', 'excerpt', 'category', 'publishedAt']) if (!meta[k]) throw new Error(`${file}: missing ${k}`);
  const content = markdown(raw.slice(fm[0].length));
  return {
    title: meta.title,
    slug: meta.slug,
    excerpt: meta.excerpt,
    category: meta.category,
    tags: (meta.tags || '').split(',').map((t) => t.trim()).filter(Boolean),
    status: 'published',
    publishedAt: new Date(meta.publishedAt).toISOString(),
    seoTitle: meta.seoTitle || '',
    seoDescription: meta.seoDescription || meta.excerpt,
    coverImage: '',
    content,
    readingTime: readingTime(content),
  };
}

const posts = fs.readdirSync(SRC).filter((f) => f.endsWith('.md')).sort().map(parse);
const slugs = new Set();
for (const p of posts) {
  if (slugs.has(p.slug)) throw new Error(`Duplicate slug ${p.slug}`);
  slugs.add(p.slug);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// GENERATED by server/scripts/build-posts.mjs from server/content/posts/*.md — edit the Markdown, then run \`npm run build:posts -w server\`.\nexport const posts = ${JSON.stringify(posts, null, 2)};\n`,
);
console.log(`✔ ${posts.length} posts → ${path.relative(process.cwd(), OUT)}`);
